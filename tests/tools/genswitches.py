# nim --fullhelp → src/ned/nim/index/switches.nim: every compiler switch, its argument and what it does
import re, subprocess, sys
out = subprocess.run(['nim', '--fullhelp'], capture_output=True, text=True).stdout
ver = re.search(r'Version (\S+)', out).group(1)
opts = []
cur = None
section = None
for line in out.splitlines():
    if re.match(r'^(Options|Advanced options):', line):
        section = 'opts'; continue
    if re.match(r'^(Advanced commands|Command|Arguments):', line):
        section = None; continue
    if section != 'opts':
        continue
    m = re.match(r'^  (-\w(?::\S+)?, )?(--[\w.\[\]-]+)(?::(\S+))?(?:\s{2,}(.*))?$', line)
    if m and line.startswith('  -'):
        short = (m.group(1) or '').strip(', ').lstrip('-').split(':')[0]
        name = m.group(2)[2:]
        arg = m.group(3) or ''
        doc = (m.group(4) or '').strip()
        cur = [name, short, arg, doc]
        opts.append(cur)
    elif cur and line.startswith('    ') and line.strip():
        cur[3] = (cur[3] + ' ' + line.strip()).strip()
    elif not line.strip():
        cur = None
def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
# (switches the help does not list, or lists in another form)
opts += [['gc', '', 'refc|orc|arc|markAndSweep|boehm|go|none|regions', 'deprecated: --mm says it now'],
         ['useVersion', '', '1.0|1.2|1.6|2.0', "emulate an older Nim's behaviour where it changed"]]
seen = set()
rows = []
for name, short, arg, doc in opts:
    if name in seen: continue
    seen.add(name)
    rows.append('  (%s, %s, %s, %s),' % (q(name), q(short), q(arg), q(doc)))
src = '''# ── the compiler's switches (`nim --fullhelp` of Nim %s): `--opt:speed` and `switch("opt", "speed")` in a
#    NimScript file completed, explained on hover and checked — generated by tests/tools/genswitches.py ──

const NxSwitches* = [
%s
]
''' % (ver, '\n'.join(rows))
open(sys.argv[1], 'w').write(src)
print(len(rows), 'switches')
