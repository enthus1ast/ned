#!/usr/bin/env python3
"""What grows: a build of ned that writes, every 30 seconds, how many entries each of its global tables, lists, sets
and strings holds — for the soak to find a leak by name, not by guessing. The tables are found in the source (every
`var` at the top of a file ned.nim includes, and the exported ones of the modules it imports), a file listing them is
written (src/ned/app/memprobe_gen.nim, and the index's own in src/ned/nim/index/: not part of the source, removed
after the build), and ned is built with -d:nedMemProbe, which includes them and calls them from the main loop and
the engine worker's. With NED_MEM_LOG=FILE set, each line of FILE is then
`seconds heapKB name=len name=len …` (and FILE.worker the same for the engine worker).

Usage: memprobe.py OUT            builds OUT (a ned with the probe; about 7 minutes)
       memprobe.py --diff LOG     the entries that grew the most between the first quarter of LOG and its end
Then:  python3 tests/soak/soak.py OUT --minutes 30 --mem-log /tmp/mem.log; memprobe.py --diff /tmp/mem.log"""
import os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(REPO, 'src')
GEN = os.path.join(SRC, 'ned', 'app', 'memprobe_gen.nim')
GENIX = os.path.join(SRC, 'ned', 'nim', 'index', 'memprobe_gen.nim')   # (the index's own, from inside its module)
INITS = re.compile(r'^  ([A-Za-z_]\w*\*?)\s*=\s*(initTable|initOrderedTable|initHashSet|initCountTable|initDeque|newSeq|@\[|"")')
SIZED = re.compile(r'^\s*(Table|OrderedTable|CountTable|HashSet|OrderedSet|seq|Deque|string)\b')

def includes():
    """the files ned.nim includes before its main loop (app/main), in order"""
    out = []
    for l in open(os.path.join(SRC, 'ned.nim'), encoding='utf-8'):
        m = re.match(r'include\s+(.+)', l)
        if not m: continue
        for part in m.group(1).split(','):
            p = part.strip()
            if p == 'ned/app/main': return out
            if p: out.append(os.path.join(SRC, p + '.nim'))
    return out

def var_names(path, exported_only):
    """(name, type) of each variable a file declares at its top level whose type has a length"""
    out = []
    invar = False
    for l in open(path, encoding='utf-8', errors='replace'):
        l = l.rstrip('\n')
        if re.match(r'^var\b', l):
            invar = True
            l = l[3:]
            if not l.strip(): continue
            l = '  ' + l.strip()
        elif l and not l[0].isspace():
            invar = False
            continue
        if not invar: continue
        mi = INITS.match(l)
        if mi:
            n = mi.group(1)
            if not (exported_only and not n.endswith('*')): out.append((n.rstrip('*'), mi.group(2)))
            continue
        m = re.match(r'^  ([A-Za-z_][\w, *]*?)\s*:\s*([^=#]+)', l)
        if not m: continue
        typ = m.group(2).strip()
        if not SIZED.match(typ): continue
        for n in m.group(1).split(','):
            n = n.strip()
            if not n: continue
            star = n.endswith('*')
            n = n.rstrip('*').strip()
            if exported_only and not star: continue
            out.append((n, typ))
    return out

def generate(skip):
    seen, names = set(), []
    for f in includes():
        if not os.path.exists(f): continue
        for n, t in var_names(f, False):
            if n not in seen and n not in skip:
                seen.add(n); names.append(n)
    # (the exported ones of the C index; the Nim index's, its own too, from inside it: nxMemProbe)
    for root, _, fs in os.walk(os.path.join(SRC, 'ned', 'c')):
        for f in sorted(fs):
            if f.endswith('.nim'):
                for n, t in var_names(os.path.join(root, f), True):
                    if n not in seen and n not in skip:
                        seen.add(n); names.append(n)
    ix = []
    ixdir = os.path.join(SRC, 'ned', 'nim', 'index')
    for f in sorted(os.listdir(ixdir)):
        if f.endswith('.nim') and f != 'memprobe_gen.nim':
            for n, t in var_names(os.path.join(ixdir, f), False):
                if n not in ix and n not in skip and n not in seen: ix.append(n)
    with open(GENIX, 'w') as g:
        g.write('# ── generated by tests/memory/memprobe.py (not part of the source): how many entries each of the index\'s\n'
                '#    tables, lists, sets and strings holds, and the names its shared layers and its scopes keep ──\n\n'
                'proc nxMemProbe*(): string =\n'
                '  ## the sizes, as `name=len` words\n'
                '  var lr, so = 0\n'
                '  for _, l in nxLayers: lr += l.refs.len\n'
                '  for _, sc in nxScopes: so += sc.refs.own.len\n'
                '  result = " ix.layerRefs=" & $lr & " ix.scopeOwn=" & $so\n')
        for n in ix:
            g.write('  result.add " ix.%s=" & $%s.len\n' % (n, n))
    with open(GEN, 'w') as g:
        g.write('# ── generated by tests/memory/memprobe.py (not part of the source): every 30 s, with NED_MEM_LOG set, a line\n'
                '#    of how many entries each global table, list, set and string holds — the soak finds what grows ──\n\n'
                'var memProbeAt: MonoTime\nvar memProbeStart = getMonoTime()\n\n'
                'proc memProbeTick(suffix: string) =\n'
                '  ## a line of sizes into NED_MEM_LOG (the engine worker: NED_MEM_LOG.worker), at most every 30 s\n'
                '  if memProbeAt != default(MonoTime) and msSince(memProbeAt) < 30_000: return\n'
                '  memProbeAt = getMonoTime()\n'
                '  let f = getEnv("NED_MEM_LOG")\n'
                '  if f.len == 0: return\n'
                '  var s = $(msSince(memProbeStart) div 1000) & " " & $(getOccupiedMem() div 1024)\n')
        for n in names:
            g.write('  s.add " %s=" & $%s.len\n' % (n, n))
        g.write('  s.add nxMemProbe()\n')
        g.write('  try:\n    let fh = open(f & suffix, fmAppend)\n    fh.writeLine(s)\n    fh.close()\n'
                '  except CatchableError: discard\n')
    return names

def build(out):
    skip = set()
    env = dict(os.environ)
    for attempt in range(6):
        names = generate(skip)
        r = subprocess.run(['nim', 'check', '--hints:off', '--warnings:off', '--errorMax:400', '-d:release',
                            '-d:nedMemProbe', 'src/ned.nim'], cwd=REPO, capture_output=True, text=True, env=env)
        bad = set()
        for gen in (GEN, GENIX):
            gl = open(gen).read().split('\n')
            pat = re.escape(os.path.relpath(gen, os.path.dirname(gen)))
            for m in re.finditer(r'(\S*)' + pat + r'\((\d+), \d+\) Error', r.stdout + r.stderr):
                if ('index' in m.group(1)) != (gen == GENIX): continue
                k = int(m.group(2)) - 1
                mm = re.search(r'add " (?:ix\.)?(\w+)=', gl[k]) if 0 <= k < len(gl) else None
                if mm: bad.add(mm.group(1))
        if not bad and 'Error' not in (r.stdout + r.stderr):
            break
        if not bad:
            sys.exit('nim check failed outside the probe:\n' + (r.stdout + r.stderr)[-3000:])
        skip |= bad
        print('(%d left out: %s)' % (len(bad), ', '.join(sorted(bad))[:300]), flush=True)
    print('%d tables, lists, sets and strings measured' % len(names), flush=True)
    r = subprocess.run(['nim', 'c', '-d:release', '--hints:off', '-d:nedMemProbe', '--nimcache:' + os.path.join(
        os.environ.get('TMPDIR', '/tmp'), 'ned-memprobe-cache'), '-o:' + os.path.abspath(out), 'src/ned.nim'], cwd=REPO)
    if r.returncode != 0: sys.exit('the build failed')
    print('built ' + out)
    for gen in (GEN, GENIX):
        os.remove(gen)              # (not part of the source: the formatter's self-test and the comment check read it)

def diff(log):
    rows = []
    for l in open(log):
        parts = l.split()
        if len(parts) < 2: continue
        d = {'heapKB': int(parts[1])}
        for p in parts[2:]:
            k, _, v = p.partition('=')
            try: d[k] = int(v)
            except ValueError: pass
        rows.append((int(parts[0]), d))
    if len(rows) < 4: sys.exit('too few lines in ' + log)
    a = rows[len(rows) // 4][1]
    b = rows[-1][1]
    print('from %d s to %d s:' % (rows[len(rows) // 4][0], rows[-1][0]))
    grew = sorted(((b[k] - a.get(k, 0), k) for k in b if b[k] - a.get(k, 0) > 0), reverse=True)
    for g, k in grew[:40]:
        print('  %-28s %10d → %-10d (+%d)' % (k, a.get(k, 0), b[k], g))

if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == '--diff':
        try: diff(sys.argv[2])
        except BrokenPipeError:                       # (its output cut short by `| head`: no traceback for it)
            os.dup2(os.open(os.devnull, os.O_WRONLY), sys.stdout.fileno())
    elif len(sys.argv) == 2 and not sys.argv[1].startswith('-'): build(sys.argv[1])
    else: sys.exit(__doc__)
